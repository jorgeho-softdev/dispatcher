import PDFDocument from 'pdfkit';

export interface RateConfirmationData {
  tripCode: string;
  isSimulated: boolean;
  carrierName: string;
  brokerName: string;
  origin: string;
  destination: string;
  pickupAt: Date;
  equipment: string;
  weightKg: number;
  distanceKm: number;
  rate: number;
  currency: 'CAD' | 'USD';
  bookedAt: Date;
  reference: string;
}

const money = (n: number, c: 'CAD' | 'USD') =>
  `${c === 'CAD' ? 'CA$' : 'US$'}${n.toLocaleString('en-CA', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/**
 * Booking / Rate Confirmation PDF. English on purpose: it's a commercial
 * document exchanged with brokers. Loads from the simulated broker are
 * watermarked as DEMO so the PDF can never pass as a real confirmation.
 */
export function renderRateConfirmation(
  d: RateConfirmationData,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'LETTER',
      margin: 56,
      info: { Title: `Rate Confirmation ${d.tripCode}` },
    });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    if (d.isSimulated) {
      doc
        .save()
        .rotate(-30, { origin: [306, 396] })
        .fontSize(96)
        .fillColor('#DC2626')
        .opacity(0.12)
        .text('DEMO', 120, 340, { width: 400, align: 'center' })
        .restore();
      doc.opacity(1);
    }

    doc
      .fillColor('#FF7A00')
      .fontSize(22)
      .font('Helvetica-Bold')
      .text('AI Dispatcher');
    doc
      .fillColor('#111216')
      .fontSize(16)
      .text(`Rate Confirmation — ${d.tripCode}`);
    if (d.isSimulated) {
      doc
        .moveDown(0.3)
        .fontSize(10)
        .fillColor('#DC2626')
        .font('Helvetica-Bold')
        .text('SIMULATED LOAD — NOT A REAL BOOKING. FOR DEMONSTRATION ONLY.');
    }
    doc
      .moveDown()
      .font('Helvetica')
      .fontSize(10)
      .fillColor('#6B6D7B')
      .text(`Reference: ${d.reference}`)
      .text(
        `Booked: ${d.bookedAt.toISOString().replace('T', ' ').slice(0, 16)} UTC`,
      );

    const row = (label: string, value: string) => {
      doc
        .moveDown(0.6)
        .fontSize(9)
        .fillColor('#6B6D7B')
        .font('Helvetica')
        .text(label.toUpperCase());
      doc.fontSize(12).fillColor('#111216').font('Helvetica-Bold').text(value);
    };
    doc.moveDown();
    row('Carrier', d.carrierName);
    row('Broker', d.brokerName);
    row(
      'Pickup',
      `${d.origin} — ${d.pickupAt.toISOString().replace('T', ' ').slice(0, 16)} UTC`,
    );
    row('Delivery', d.destination);
    row(
      'Equipment / weight',
      `${d.equipment} · ${d.weightKg.toLocaleString('en-CA')} kg`,
    );
    row('Distance', `${d.distanceKm.toLocaleString('en-CA')} km`);
    row('Agreed rate (all-in)', money(d.rate, d.currency));

    doc
      .moveDown(2)
      .fontSize(8)
      .fillColor('#6B6D7B')
      .font('Helvetica')
      .text(
        'Generated by AI Dispatcher from the agreed negotiation. Payment terms, accessorials and liability follow the broker-carrier agreement.',
      );
    doc.end();
  });
}
